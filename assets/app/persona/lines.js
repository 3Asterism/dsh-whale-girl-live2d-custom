const LINES = { ...CORE_LINES, ...BOND_LINES }

/**
 * 取一句台词：按台词档分（有分档池时 70% 用本档，其余用通用池），同池不连续重复。
 * `vars` 里的 {n} {name} 会被替换。没有这个 id 返回 undefined（调用方按「不说话」处理）。
 */
export function lineFor(id, vars) {
  const e = LINES[id]
  if (!e) return undefined
  let pool = e
  if (!Array.isArray(e)) {
    const mine = e.lv && e.lv[bond.tier]
    pool = mine && mine.length && Math.random() < 0.7 ? mine : e.pool && e.pool.length ? e.pool.concat(mine || []) : mine || []
  }
  let s = pickFresh(pool, 'L-' + id)
  if (s && vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]))
  return s
}
